export const calculateStars = (wpm: number, accuracy: number, level: Level): number => {
  const requiredWpm = level.unlockRequirement.wpm;
  const requiredAccuracy = level.unlockRequirement.accuracy;

  if (wpm >= requiredWpm + 15 && accuracy >= 98) return 3;
  if (wpm >= requiredWpm + 8 && accuracy >= 95) return 2;
  if (wpm >= requiredWpm && accuracy >= requiredAccuracy) return 1;
  return 0;
};

export const canUnlockLevel = (
  levelId: number,
  progress: LevelProgress[]
): boolean => {
  if (levelId === 1) return true;

  const previousLevel = progress.find((p) => p.levelId === levelId - 1);
  if (!previousLevel) return false;

  return previousLevel.completed;
};
